import * as React from "react";
import * as AvatarPrimitive from "@radix-ui/react-avatar";
import { cn } from "@/lib/utils-ui";
const Avatar=React.forwardRef(function Avatar({className,...props},ref){return <AvatarPrimitive.Root ref={ref} className={cn("relative flex size-8 shrink-0 overflow-hidden rounded-full border border-border/70 bg-muted",className)} {...props}/>;});
Avatar.displayName=AvatarPrimitive.Root.displayName;
const AvatarImage=React.forwardRef(function AvatarImage({className,...props},ref){return <AvatarPrimitive.Image ref={ref} className={cn("aspect-square size-full object-cover",className)} {...props}/>;});
AvatarImage.displayName=AvatarPrimitive.Image.displayName;
const AvatarFallback=React.forwardRef(function AvatarFallback({className,...props},ref){return <AvatarPrimitive.Fallback ref={ref} className={cn("flex size-full items-center justify-center rounded-full bg-secondary text-xs font-medium text-secondary-foreground",className)} {...props}/>;});
AvatarFallback.displayName=AvatarPrimitive.Fallback.displayName;
export {Avatar,AvatarImage,AvatarFallback};
